import { z } from 'zod';
import {validProjectTime, projectTimeRangeValid, projectTimes} from './project-time.mjs';

const photoSchema = z.object({
  src: z.string(),
  caption: z.string().optional(),
  alt: z.string().optional(),
});

export const schemas = {
  profile: z.object({
    name: z.string(),
    nameEn: z.string().optional(),
    title: z.string(),
    affiliation: z.string(),
    email: z.string().email(),
    phone: z.string().optional(),
    office: z.string().optional(),
    photo: z.string().optional(),
    bio: z.string().optional(),
    tagline: z.string().optional(),
    highlights: z.array(z.object({
      role: z.string(),
      organization: z.string(),
      period: z.string().optional(),
    })).optional(),
    education: z.array(z.object({
      degree: z.string(),
      school: z.string(),
      field: z.string().optional(),
      year: z.number(),
    })).optional(),
    experience: z.array(z.object({
      role: z.string(),
      organization: z.string(),
      period: z.string(),
      order: z.number().default(0),
    })).optional(),
    schools: z.array(z.string()).optional(),
    researchAreas: z.array(z.string()),
    interests: z.array(z.string()).optional(),
    cvUrl: z.string().optional(),
    photos: z.array(photoSchema).optional(),
    links: z.array(z.object({
      label: z.string(),
      url: z.string().url(),
    })).optional(),
  }),
  lab: z.object({
    name: z.string(),
    nameEn: z.string(),
    intro: z.string(),
    introEn: z.string().optional(),
    researchTopics: z.array(z.string()).optional(),
    mission: z.array(z.string()).optional(),
    email: z.string().email(),
    phone: z.string().optional(),
    office: z.string().optional(),
    address: z.string().optional(),
    addressEn: z.string().optional(),
    campusMap: z.string().optional(),
    photos: z.array(photoSchema).optional(),
    links: z.array(z.object({
      label: z.string(),
      url: z.string().url(),
    })).optional(),
  }),
  photos: z.object({
    caption: z.string(),
    src: z.string(),
    alt: z.string().optional(),
    category: z.enum(['實驗室', '學術活動', '獲獎典禮', '師生合影', '其他']),
    year: z.number().optional(),
    order: z.number().default(0),
  }),
  publications: z.object({
    bibType: z.string().optional(),
    bibKey: z.string().optional(),
    type: z.enum(['journal', 'conference', 'book-chapter', 'book', 'other']).optional(),
    title: z.string(),
    authors: z.union([z.string(), z.array(z.string()).min(1)]),
    venue: z.string().optional(),
    journal: z.string().optional(),
    booktitle: z.string().optional(),
    editors: z.array(z.string()).optional(),
    series: z.string().optional(),
    isbn: z.string().optional(),
    eventDate: z.string().optional(),
    location: z.string().optional(),
    howPublished: z.string().optional(),
    volume: z.string().optional(),
    issue: z.string().optional(),
    pages: z.string().optional(),
    month: z.string().optional(),
    indexes: z.array(z.string()).optional(),
    url: z.union([z.literal(''), z.string().url()]).optional(),
    ee: z.union([z.literal(''), z.string().url()]).optional(),
    eprint: z.union([z.literal(''), z.string().url()]).optional(),
    issn: z.string().optional(),
    publisher: z.string().optional(),
    address: z.string().optional(),
    note: z.string().optional(),
    keywords: z.array(z.string()).optional(),
    issueDate: z.string().optional(),
    pageCount: z.string().optional(),
    acmid: z.string().optional(),
    bibSource: z.string().optional(),
    bibUrl: z.string().optional(),
    owner: z.string().optional(),
    timestamp: z.string().optional(),
    addedAt: z.string().optional(),
    interhash: z.string().optional(),
    intrahash: z.string().optional(),
    year: z.number(),
    link: z.string().url().optional(),
    doi: z.string().optional(),
    links: z.array(z.object({ label: z.string(), url: z.string().url() })).optional(),
    abstract: z.string().optional(),
    order: z.number().default(0),
  }),
  projects: z.object({
    bibKey: z.string().optional(),
    bibType: z.string().optional(),
    type: z.literal('project').optional(),
    sourceTitle: z.string().optional(),
    year: z.number().optional(),
    authors: z.array(z.string()).optional(),
    institution: z.string().optional(),
    projectType: z.string().optional(),
    note: z.string().optional(),
    owner: z.string().optional(),
    timestamp: z.string().optional(),
    url: z.union([z.literal(''), z.string().url()]).optional(),
    category: z.enum(['研究型', '教學服務型', '大專生']).optional(),
    title: z.string(),
    grant: z.string().optional(),
    status: z.enum(['進行中', '已完成']),
    startTime: z.string().refine(validProjectTime, '請填西元年份、年/月或年/月/日，例如 2021、2021/08、2021/08/01').optional(),
    endTime: z.string().refine(validProjectTime, '請填有效的年份、年月或日期').optional(),
    startYear: z.number().optional(),
    endYear: z.number().optional(),
    funding: z.string().optional(),
    projectUrl: z.string().url().refine(value => {try {const url = new URL(value); return url.protocol === 'https:' && !url.username && !url.password;} catch {return false;}}, '請填寫 HTTPS 計畫詳細頁面網址').optional(),
    image: z.string().optional(),
    detail: z.string().optional(),
    role: z.string().optional(),
    period: z.string().optional(),
    sourceUrl: z.string().url().optional(),
    order: z.number().default(0),
  }).refine(row => row.startTime !== undefined || row.startYear !== undefined, {message:'請填開始時間',path:['startTime']}).refine(row => row.status !== '已完成' || Boolean(projectTimes(row).endTime), {message:'已完成的計畫請填結束時間，只填年份也可以',path:['endTime']}).refine(projectTimeRangeValid, {message:'結束時間不可早於開始時間',path:['endTime']}),
  graduates: z.object({
    student: z.string(),
    thesis: z.string(),
    degree: z.string().optional(),
    link: z.string().url().optional(),
    year: z.number(),
    order: z.number().default(0),
  }),
  awards: z.object({
    title: z.string(),
    /** 獎項名稱（可手動覆寫自動解析結果） */
    award: z.string().optional(),
    sourceUrl: z.string().url().optional(),
    recipient: z.string().optional(),
    organization: z.string().optional(),
    year: z.number(),
    image: z.string().optional(),
    detail: z.string().optional(),
    order: z.number().default(0),
  }),
  services: z.object({
    role: z.string(),
    organization: z.string(),
    category: z.enum(['校內行政', '校內職務', '教學營隊', '國際服務']).optional(),
    startYear: z.number(),
    endYear: z.number().optional(),
    order: z.number().default(0),
  }),
  academics: z.object({
    title: z.string(),
    organization: z.string(),
    category: z.enum(['學會會員', '期刊審稿', '會議委員', '國際會議', '國內會議']).optional(),
    startYear: z.number(),
    endYear: z.number().optional(),
    image: z.string().optional(),
    order: z.number().default(0),
  }),
  honors: z.object({
    title: z.string(),
    organization: z.string().optional(),
    year: z.number(),
    order: z.number().default(0),
    image: z.string().optional(),
    detail: z.string().optional(),
  }),
};
